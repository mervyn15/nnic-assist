import {build,transform} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const css=await readFile('src/styles.css','utf8');
const check=await transform(css,{loader:'css',logLevel:'silent'});
if(check.warnings.length) throw new Error(check.warnings.map(w=>w.text).join('\n'));
if(/@import\s|url\(["']?https?:/i.test(css)) throw new Error('The demo must work without a CDN');
const bundle=await build({entryPoints:['src/main.tsx'],bundle:true,write:false,format:'iife',platform:'browser',jsx:'automatic',minify:true,define:{'process.env.NODE_ENV':'"production"'}});
const js=bundle.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
await writeFile('index.html',`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#ffffff"><title>NNIC Assist | Guided demo</title><style>${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`);
console.log('Built index.html. PDFs use relative links to the existing reports directory.');
